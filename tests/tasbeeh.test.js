// tests/tasbeeh.test.js
import assert from 'assert';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.join(__dirname, '..');

export async function runTasbeehTests() {
    console.log('▶ Running TasbeehStore & Data Model Tests...');

    // Minimal Mock for Knockout
    globalThis.ko = {
        observable(init) {
            let v = init;
            const subs = [];
            const fn = function(newVal) {
                if (arguments.length > 0) {
                    if (v !== newVal) {
                        v = newVal;
                        subs.forEach(s => s(v));
                    }
                    return fn;
                }
                return v;
            };
            fn.subscribe = function(cb) { subs.push(cb); return { dispose() {} }; };
            fn.__ko_proto__ = fn;
            return fn;
        },
        observableArray(init) {
            const obs = globalThis.ko.observable(init || []);
            obs.push = function(...args) {
                const arr = obs();
                arr.push(...args);
                obs(arr);
            };
            return obs;
        },
        pureComputed(readOrOpts) {
            const read = typeof readOrOpts === 'function' ? readOrOpts : (readOrOpts && readOrOpts.read);
            const write = (readOrOpts && typeof readOrOpts.write === 'function') ? readOrOpts.write : function() {};
            const fn = function(val) {
                if (arguments.length > 0) {
                    write(val);
                    return fn;
                }
                return read ? read() : undefined;
            };
            fn.__ko_proto__ = fn;
            fn.subscribe = function() { return { dispose() {} }; };
            return fn;
        },
        computed(read) { return globalThis.ko.pureComputed(read); },
        isObservable(fn) { return typeof fn === 'function' && !!fn.__ko_proto__; }
    };

    const { normalizeItem, isMonthFullyCompleted, getDaysInMonth, getCompletedDaysInMonth } = await import(path.join(ROOT, 'tasbeeh', 'tasbeeh-model.js'));
    const { TasbeehStore } = await import(path.join(ROOT, 'services', 'tasbeeh-store.js'));

    // 1. Item Normalization
    const item1 = normalizeItem({ title: 'SubhanAllah', targetCount: 33 });
    assert.strictEqual(item1.title, 'SubhanAllah');
    assert.strictEqual(item1.targetCount, 33);
    assert(item1.id, 'Item must have an autogenerated id');

    const itemInf = normalizeItem({ title: 'Chant', targetCount: 'infinite' });
    assert.strictEqual(itemInf.targetCount, 'infinite');

    // 2. TasbeehStore items and computeds
    const testItems = [
        { id: '1', title: 'SubhanAllah', targetCount: 33, currentCount: 33, dailyHistory: { '2026-11-06': 33 } },
        { id: '2', title: 'Alhamdulillah', targetCount: 33, currentCount: 0, dailyHistory: {} },
        { id: '3', title: 'Allahu Akbar', targetCount: 34, currentCount: 0, dailyHistory: {} }
    ];

    TasbeehStore.items(testItems);

    assert.strictEqual(TasbeehStore.currentDhikrsCount(), 3);
    assert.strictEqual(TasbeehStore.currentTodoItems().length, 2);
    assert.strictEqual(TasbeehStore.currentDoneItems().length, 1);
    assert.strictEqual(TasbeehStore.dailyProgress(), 33, '1 out of 3 done is ~33%');

    // 3. Month Completion Logic
    const calCompletions = {
        '1': {}
    };
    // Mark all 30 days of 2026-09 completed
    for (let d = 1; d <= 30; d++) {
        const ds = '2026-09-' + (d < 10 ? '0' + d : d);
        calCompletions['1'][ds] = true;
    }

    const septDays = getDaysInMonth(2026, 8); // 8 = September (0-indexed)
    assert.strictEqual(septDays, 30);
    const completedDays = getCompletedDaysInMonth(calCompletions, '1', 2026, 8);
    assert.strictEqual(completedDays, 30);

    const isSeptDone = isMonthFullyCompleted(calCompletions, [{ id: '1', targetCount: 33 }], '2026-09');
    assert.strictEqual(isSeptDone, true, 'September should be fully completed');

    // 4. TasbeehCounterCardViewModel robustness
    const { TasbeehCounterCardViewModel, TasbeehPageViewModel } = await import(path.join(ROOT, 'tasbeeh', 'tasbeeh-view-model.js'));
    const cardVm = new TasbeehCounterCardViewModel({ id: 't1', title: 'Test Dhikr' });
    assert.strictEqual(cardVm.id, 't1');
    assert.strictEqual(cardVm.title, 'Test Dhikr');
    assert.strictEqual(cardVm.isComplete, false, 'isComplete must default to false without ReferenceError');
    assert.strictEqual(cardVm.totalDays, 30);
    assert.strictEqual(typeof cardVm.onCardClick, 'function');
    assert.strictEqual(typeof cardVm.onEditClick, 'function');

    // 5. Current Tab Observable Arrays & Completion Transition
    const pageVm = new TasbeehPageViewModel();
    assert(Array.isArray(pageVm.currentTodoItems()), 'currentTodoItems must be an array observable');
    assert(Array.isArray(pageVm.currentDoneItems()), 'currentDoneItems must be an array observable');

    // Initially simulate 2 To Do items and 0 Completed items
    pageVm.currentTodoItems([{ id: 'c1', title: 'SubhanAllah' }, { id: 'c2', title: 'Alhamdulillah' }]);
    pageVm.currentDoneItems([]);
    assert.strictEqual(pageVm.currentTodoItems().length, 2);
    assert.strictEqual(pageVm.currentDoneItems().length, 0);

    // Marking item c1 as completed moves it from To Do to Completed tab
    pageVm.currentTodoItems([{ id: 'c2', title: 'Alhamdulillah' }]);
    pageVm.currentDoneItems([{ id: 'c1', title: 'SubhanAllah', isComplete: true }]);
    assert.strictEqual(pageVm.currentTodoItems().length, 1);
    assert.strictEqual(pageVm.currentDoneItems().length, 1);
    assert.strictEqual(pageVm.currentDoneItems()[0].id, 'c1');

    console.log('  ✔ TasbeehStore: Items, progress computeds, month completion, card VM, and current tab completion passed');
}
