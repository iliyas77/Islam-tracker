    // ===== STORAGE KEYS =====
    var STORAGE_KEY_DUAS = 'quranDuas_data';
    var STORAGE_KEY_FAVS = 'quranDuas_favourites';
    var STORAGE_KEY_PINS = 'quranDuas_pins';
    var MAX_PINS = 2;

    // ===== STATE =====
    var duasData = [];
    var favourites = [];
    var pins = [];
    var currentIndex = 0;
    var activeTab = 'home'; // 'home' | 'duas' | 'favourites'
    var detailOpenedFrom = 'home';
    var pendingPinIndex = null;
